import { test, expect, type Page } from '@playwright/test';
import { randomUUID } from 'node:crypto';

async function saved(page: Page, path: string) {
  const [response] = await Promise.all([page.waitForResponse(row => new URL(row.url()).pathname === path && row.request().method() === 'POST'), page.getByRole('button', { name: 'Enregistrer la fiche', exact: true }).click()]);
  expect(response.ok(), await response.text()).toBeTruthy();
  return await response.json() as { id: string; status: string; membership_id?: string | null };
}

test('employés sans compte, département, mission et accès existant restent distincts', async ({ page }, info) => {
  page.on('dialog', dialog => void dialog.accept());
  const errors: string[] = []; let registrations = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/v1/auth/register/' && request.method() === 'POST') registrations++; });
  await page.goto('/register');
  await page.getByLabel('Nom complet', { exact: true }).fill('Administrateur E2E équipe');
  await page.getByLabel('E-mail', { exact: true }).fill(`qa-people-${randomUUID()}@example.invalid`);
  await page.getByLabel('Mot de passe', { exact: true }).fill('Qavelys-E2E!2026-Only');
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Créer une entreprise', exact: true })).toBeVisible();
  await page.getByLabel('Nom de l’entreprise', { exact: true }).fill('E2E Équipe et missions');
  await page.getByLabel('Pays (code à 2 lettres)', { exact: true }).fill('FR');
  await page.getByLabel('Devise principale', { exact: true }).fill('EUR');
  await page.getByRole('button', { name: 'Créer mon espace administrateur', exact: true }).click();
  await expect(page).toHaveURL(/\/administration\/entreprises\/[0-9a-f-]+$/);
  const base = new URL(page.url()).pathname; const companyId = base.split('/').at(-1)!; const api = `/api/v1/companies/${companyId}/`;
  await page.goto(`${base}/modules`);
  const module = page.locator('.module-grid > section').filter({ has: page.getByRole('heading', { name: 'Équipe et missions', exact: true }) });
  await module.getByRole('button', { name: 'Activer avec ses dépendances', exact: true }).click();
  await expect(module.getByRole('button', { name: 'Désactiver', exact: true })).toBeVisible();
  await page.goto(`${base}/departements/nouveau`);
  await page.getByLabel('Nom du département', { exact: true }).fill('Atelier principal');
  const department = await saved(page, api + 'hr/departments/');
  await expect(page.getByRole('heading', { name: 'Atelier principal', exact: true })).toBeVisible();
  await page.goto(`${base}/employes/nouveau`);
  await page.getByLabel('Matricule', { exact: true }).fill('EMP-E2E');
  await page.getByLabel('Nom complet de l’employé', { exact: true }).fill('Aminata Diallo');
  await page.getByLabel('Poste', { exact: true }).fill('Responsable atelier');
  await page.getByLabel('Département', { exact: true }).selectOption(department.id);
  await page.getByLabel('Responsabilités', { exact: true }).fill('Organiser les contrôles de l’atelier.');
  const employee = await saved(page, api + 'hr/employees/');
  expect(employee.membership_id).toBeNull();
  await expect(page.getByText('Sans accès Qavelys', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Attribuer une mission', exact: true }).click();
  await expect(page.getByLabel('Employé affecté', { exact: true })).toHaveValue(employee.id);
  await page.getByLabel('Intitulé de la mission', { exact: true }).fill('Contrôler les équipements');
  await page.getByLabel('Échéance', { exact: true }).fill('2026-12-01');
  const mission = await saved(page, api + 'hr/missions/');
  await page.getByRole('button', { name: 'Démarrer', exact: true }).click();
  await expect(page.locator('.page-heading')).toContainText('En cours');
  await page.getByRole('button', { name: 'Terminer', exact: true }).click();
  await expect(page.locator('.page-heading')).toContainText('Terminée');
  const persistedMission = await (await page.request.get(api + `hr/missions/${mission.id}/`)).json() as { completed_at: string };
  expect(persistedMission.completed_at).toBeTruthy();
  await page.goto(`${base}/employes/${employee.id}/modifier`);
  const members = await (await page.request.get(api + 'members/')).json() as { id: string; full_name: string }[];
  expect(members).toHaveLength(1);
  await page.getByLabel('Accès utilisateur Qavelys facultatif', { exact: true }).selectOption(members[0].id);
  await saved(page, api + `hr/employees/${employee.id}/`);
  await expect(page.getByText('Accès utilisateur lié', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Archiver', exact: true }).click();
  await expect(page.locator('.page-heading')).toContainText('Archivé');
  const membersAfter = await (await page.request.get(api + 'members/')).json() as { id: string; full_name: string; status: string }[];
  expect(membersAfter[0].status).toBe('active');
  expect(membersAfter[0].full_name).toBe('Administrateur E2E équipe');
  expect(registrations).toBe(1);
  await page.screenshot({ path: info.outputPath('employe-archive-acces-conserve.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Activer le thème sombre', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: info.outputPath('employe-mobile-sombre.png'), fullPage: true });
  expect(errors).toEqual([]);
});
