import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('administration lisible : modèles de rôles, permissions, numérotation et audit réels', async ({ page }, info) => {
  page.on('dialog', dialog => void dialog.accept());
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/register');
  await page.getByLabel('Nom complet', { exact: true }).fill('Administrateur E2E lisibilité');
  await page.getByLabel('E-mail', { exact: true }).fill(`qa-admin-${randomUUID()}@example.invalid`);
  await page.getByLabel('Mot de passe', { exact: true }).fill('Qavelys-E2E!2026-Only');
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Créer une entreprise', exact: true })).toBeVisible();
  await page.getByLabel('Nom de l’entreprise', { exact: true }).fill('E2E Administration lisible');
  await page.getByLabel('Pays (code à 2 lettres)', { exact: true }).fill('FR');
  await page.getByLabel('Devise principale', { exact: true }).fill('EUR');
  await page.getByRole('button', { name: 'Créer mon espace administrateur', exact: true }).click();
  await expect(page).toHaveURL(/\/administration\/entreprises\/[0-9a-f-]+$/);
  const base = new URL(page.url()).pathname;
  const companyId = base.split('/').at(-1)!;
  await page.goto(`${base}/roles`);
  await page.getByRole('button', { name: 'Ajouter · Commercial', exact: true }).click();
  await expect(page.getByText('Déjà disponible', { exact: true })).toBeVisible();
  const roleForm = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Créer un rôle', exact: true }) });
  await roleForm.getByLabel('Nom du rôle', { exact: true }).fill('Lecteur de ventes E2E');
  await roleForm.getByRole('button', { name: 'Tout sélectionner · Ventes', exact: true }).click();
  await expect(roleForm.getByRole('checkbox', { name: 'Consulter les documents de ventes', exact: true })).toBeChecked();
  await roleForm.getByRole('button', { name: 'Tout retirer · Ventes', exact: true }).click();
  await roleForm.getByRole('checkbox', { name: 'Consulter les documents de ventes', exact: true }).check();
  await roleForm.getByRole('button', { name: 'Enregistrer le rôle', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Lecteur de ventes E2E', exact: true })).toBeVisible();
  const roles = await (await page.request.get(`/api/v1/companies/${companyId}/roles/`)).json() as { name: string; permission_codes: string[] }[];
  expect(roles.find(row => row.name === 'Lecteur de ventes E2E')?.permission_codes).toEqual(['sales.order.view']);
  await page.goto(`${base}/sequences`);
  await page.getByRole('button', { name: 'Configurer · Factures clients', exact: true }).click();
  await page.getByLabel('Préfixe · Factures clients', { exact: true }).fill('E2EFAC-');
  await expect(page.getByText('Aperçu : E2EFAC-000001', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Enregistrer le préfixe', exact: true }).click();
  await expect(page.getByText('E2EFAC-000001', { exact: true })).toBeVisible();
  await page.goto(`${base}/audit`);
  await page.getByLabel('Rechercher une action, une personne ou un document', { exact: true }).fill('Factures clients');
  const event = page.getByRole('row').filter({ hasText: 'Modification · Numérotation' });
  await expect(event).toBeVisible();
  await event.getByText('Consulter les changements', { exact: true }).click();
  await expect(event.getByText('E2EFAC-', { exact: true })).toBeVisible();
  await expect(event.locator('details').filter({ has: page.getByText('Détails techniques', { exact: true }) }).last()).not.toHaveAttribute('open', '');
  await page.screenshot({ path: info.outputPath('audit-lisible.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Activer le thème sombre', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: info.outputPath('audit-mobile-sombre.png'), fullPage: true });
  expect(errors).toEqual([]);
});
